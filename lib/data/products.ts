/** Squishy aisles sold as a priced box of 12 (listed price = box price). */
const SQUISHY_BOX_SLUGS = new Set<string>([
  "squishies",
  "jumbo-squishies",
  "sugar-squishies",
  "wax-squishies",
  "crunchy-squishies",
  "vaseline-squishies",
  "dumpling-squishies",
  "christmas-squishies",
]);

/** Squishy aisles sold each (listed price = per piece). Min order still 12 pcs. */
const SQUISHY_EACH_SLUGS = new Set<string>(["small-squishies", "butter-squishies"]);

/** Keep a non-12 MOQ only for true small packs (1-11 pcs). Factory carton labels are ignored. */
function isNonDefaultSquishyMoq(product: Product) {
  if (typeof product.piecesPerBox === "number" && product.piecesPerBox > 0 && product.piecesPerBox < 12) {
    return true;
  }
  return false;
}

export const products: Product[] = catalog.filter((product) => !HIDDEN_PRODUCT_SLUGS.includes(product.slug)).map((product) => {
  const categorySlug = assignedCategory[product.slug] ?? product.categorySlug;
  const pieces = product.piecesPerBox && product.piecesPerBox > 0 ? product.piecesPerBox : getPiecesPerBox(product) ?? 1;
  const keepCustomMoq = isNonDefaultSquishyMoq(product);
  const soldEach = SQUISHY_EACH_SLUGS.has(categorySlug);
  const boxMoq = SQUISHY_BOX_SLUGS.has(categorySlug) && !keepCustomMoq && !soldEach;
  const boxPieces = soldEach ? 1 : boxMoq ? 12 : pieces;
  const moqLabel = soldEach
    ? "Min order: 12 pcs"
    : keepCustomMoq
      ? product.moqLabel ?? `Min order: ${pieces} pcs`
      : boxMoq
        ? "Box of 12"
        : product.moqLabel ?? `Min order: ${boxPieces} pcs`;
  const features = (product.features ?? []).filter(
    (feature) =>
      !/^minimum order\b/i.test(feature.trim()) &&
      !/^min order\b/i.test(feature.trim()) &&
      !/^box of\s*\d+/i.test(feature.trim()) &&
      feature !== moqLabel,
  );
  const name = assignedName[product.slug] ?? product.name;
  const price = assignedPrice[product.slug] ?? product.price;
  const priceTBC = assignedPrice[product.slug] != null ? false : product.priceTBC;
  return {
    ...product,
    name,
    price,
    priceTBC,
    categorySlug,
    piecesPerBox: boxPieces,
    moqLabel,
    features: [moqLabel, ...features],
    images: productGallery(product.slug, categorySlug, product.images),
  };
});

